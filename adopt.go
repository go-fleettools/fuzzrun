// adoptBranch is the branch every adoption PR lives on.
const adoptBranch = "fuzzrun-workflow"

const attribution = "Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>"

const triggerMarker = "  workflow_dispatch:\n"
const triggerText = "  push:\n    branches: [" + adoptBranch + "]\n"

const (
	msgAdd = "fuzz: a nightly workflow that fuzzes every target\n\n" +
		"The nightly fuzz workflow is added, or rewritten, so that one fuzzrun step\n" +
		"fuzzes every FuzzXxx found by parsing and fails only on exit 2 (the run\n" +
		"could not be made). Generated by fuzzrun workflow (" + fuzzrunVersion + ").\n\n" + attribution + "\n"
	msgTrigger = "fuzz: temporary push trigger to verify the workflow on this branch\n\n" +
		"Removed in the next commit, before the merge.\n\n" + attribution + "\n"
	msgRemove = "fuzz: remove the temporary push trigger\n\n" +
		"The run on this branch was read: every target PASS on every job.\n\n" + attribution + "\n"
	prTitle = "fuzz: a nightly workflow that fuzzes every target"
	prBody  = "This repository's `FuzzXxx` targets were not all fuzzed anywhere beyond their seed corpus (or were listed by hand, some under `continue-on-error: true`). " +
		"The nightly `fuzz.yml` (a schedule and manual dispatch, not a pull request gate) now runs one `fuzzrun run` step: every target found by parsing, red only on exit 2, per-target logs uploaded. " +
		"Same form as go-simd/floats pull request 66, generated by `fuzzrun workflow` " + fuzzrunVersion + ". " +
		"Before the merge the workflow is run on this branch through a temporary `push` trigger, and the `N targets: N PASS, 0 FAIL, 0 CRASH` summary of every job log is read; the trigger is removed in its own commit.\n\n" +
		"🤖 Generated with [Claude Code](https://claude.com/claude-code)\n"
)

// runner is how adopt reaches git, gitpush and gh; tests replace it.
type runner interface {
	Run(dir, tool string, args ...string) (string, error)
}

type execRunner struct{}

func (execRunner) Run(dir, tool string, args ...string) (string, error) {
	path := tool
	if tool == "gitpush" {
		home, err := os.UserHomeDir()
		if err != nil {
			return "", err
		}
		path = filepath.Join(home, ".local", "bin", "gitpush")
	}
	c := exec.Command(path, args...)
	c.Dir = dir
	var out, errb bytes.Buffer
	c.Stdout, c.Stderr = &out, &errb
	if err := c.Run(); err != nil {
		return out.String(), fmt.Errorf("%s %s: %w: %s", tool, strings.Join(args, " "), err, strings.TrimSpace(errb.String()))
	}
	return out.String(), nil
}

var newRunner = func() runner { return execRunner{} }

var slugRe = regexp.MustCompile(`github\.com[:/]([^/\s]+/[^/\s]+?)(?:\.git)?\s*$`)

func repoSlug(r runner, dir string) (string, error) {
	u, err := r.Run(dir, "git", "remote", "get-url", "origin")
	if err != nil {
		return "", err
	}
	m := slugRe.FindStringSubmatch(strings.TrimSpace(u))
	if m == nil {
		return "", fmt.Errorf("origin %q is not a github.com repository", strings.TrimSpace(u))
	}
	return m[1], nil
}

func addTrigger(s string) (string, error) {
	if strings.Contains(s, triggerText) {
		return "", errors.New("the push trigger is already there")
	}
	if !strings.Contains(s, triggerMarker) {
		return "", errors.New("fuzz.yml has no workflow_dispatch trigger to put the push trigger after")
	}
	return strings.Replace(s, triggerMarker, triggerMarker+triggerText, 1), nil
}

func removeTrigger(s string) (string, error) {
	if !strings.Contains(s, triggerText) {
		return "", errors.New("the temporary push trigger is not in fuzz.yml")
	}
	return strings.Replace(s, triggerText, "", 1), nil
}

func adoptCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "adopt",
		Short: "Open, then finish, the pull request that gives a repository the fuzzrun nightly workflow",
	}
	cmd.AddCommand(adoptOpenCmd(), adoptFinishCmd())
	return cmd
}

func adoptOpenCmd() *cobra.Command {
	var dir string
	cmd := &cobra.Command{
		Use:   "open",
		Short: "Branch from origin/HEAD, write fuzz.yml, add a temporary push trigger, push, open the PR",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			r := newRunner()
			step := func(tool string, args ...string) (string, error) {
				out, err := r.Run(dir, tool, args...)
				if err != nil {
					return out, &exitError{2, err}
				}
				return out, nil
			}
			if !isModule(dir) {
				return &exitError{2, fmt.Errorf("no go.mod in %s", dir)}
			}
			if st, err := step("git", "status", "--porcelain"); err != nil {
				return err
			} else if strings.TrimSpace(st) != "" {
				return &exitError{2, errors.New("the working tree is not clean")}
			}
			slug, err := repoSlug(r, dir)
			if err != nil {
				return &exitError{2, err}
			}
			if _, err := step("git", "fetch", "origin"); err != nil {
				return err
			}
			if _, err := step("git", "checkout", "-b", adoptBranch, "origin/HEAD"); err != nil {
				return err
			}
			wf := workflowCmd()
			wf.SetArgs([]string{"--dir", dir, "--write"})
			wf.SetOut(cmd.OutOrStdout())
			wf.SetErr(cmd.ErrOrStderr())
			if err := wf.Execute(); err != nil {
				var ee *exitError
				if errors.As(err, &ee) && ee.code == 1 {
					return &exitError{2, errors.New("nothing to change: the repository already has the fuzzrun workflow (or no go test -fuzz step)")}
				}
				return &exitError{2, err}
			}
			wfPath := filepath.Join(dir, ".github", "workflows", "fuzz.yml")
			if _, err := step("git", "add", ".github/workflows/fuzz.yml"); err != nil {
				return err
			}
			if _, err := step("git", "commit", "-m", msgAdd); err != nil {
				return err
			}
			b, err := os.ReadFile(wfPath)
			if err != nil {
				return &exitError{2, err}
			}
			t, err := addTrigger(string(b))
			if err != nil {
				return &exitError{2, err}
			}
			if err := os.WriteFile(wfPath, []byte(t), 0o644); err != nil {
				return &exitError{2, err}
			}
			if _, err := step("git", "commit", "-a", "-m", msgTrigger); err != nil {
				return err
			}
			if _, err := step("gitpush", "-u", "origin", adoptBranch); err != nil {
				return err
			}
			body := filepath.Join(dir, ".git", "fuzzrun-pr-body.md")
			if err := os.WriteFile(body, []byte(prBody), 0o644); err != nil {
				return &exitError{2, err}
			}
			url, err := step("gh", "pr", "create", "--repo", slug, "--head", adoptBranch, "--title", prTitle, "--body-file", body)
			if err != nil {
				return err
			}
			fmt.Fprintln(cmd.OutOrStdout(), strings.TrimSpace(url))
			return nil
		},
	}
	cmd.Flags().StringVar(&dir, "dir", ".", "clone of the repository")
	return cmd
}

type ghRun struct {
	DatabaseID int64  `json:"databaseId"`
	HeadSHA    string `json:"headSha"`
	Status     string `json:"status"`
	Conclusion string `json:"conclusion"`
}

type ghJobs struct {
	Jobs []struct {
		Name       string `json:"name"`
		Conclusion string `json:"conclusion"`
	} `json:"jobs"`
}

var (
	summaryRe = regexp.MustCompile(`(\d+) targets: (\d+) PASS, (\d+) FAIL, (\d+) CRASH`)
	crashRe   = regexp.MustCompile(`\bCRASH (\./\S*) (Fuzz\S*) \S+ (\S+)`)
)

func adoptFinishCmd() *cobra.Command {
	var dir string
	cmd := &cobra.Command{
		Use:   "finish",
		Short: "Verify the push run of fuzz.yml on the branch head, remove the trigger, push",
		Long: `Reads the latest push run of fuzz.yml whose head is the SHA of the branch head
(read with git rev-parse), and refuses (exit 2) unless it is completed, every job
concluded success and every job log carries "N targets: N PASS, 0 FAIL, 0 CRASH".
A crasher is printed and exits 1. Otherwise the temporary push trigger is removed,
committed and pushed, and the exit status is 0.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			out := cmd.OutOrStdout()
			r := newRunner()
			run := func(tool string, args ...string) (string, error) {
				o, err := r.Run(dir, tool, args...)
				if err != nil {
					return o, &exitError{2, err}
				}
				return o, nil
			}
			br, err := run("git", "rev-parse", "--abbrev-ref", "HEAD")
			if err != nil {
				return err
			}
			if strings.TrimSpace(br) != adoptBranch {
				return &exitError{2, fmt.Errorf("HEAD is on %q, not %s", strings.TrimSpace(br), adoptBranch)}
			}
			shaOut, err := run("git", "rev-parse", "HEAD")
			if err != nil {
				return err
			}
			sha := strings.TrimSpace(shaOut)
			slug, err := repoSlug(r, dir)
			if err != nil {
				return &exitError{2, err}
			}
			lj, err := run("gh", "run", "list", "--repo", slug, "--workflow", "fuzz.yml", "--branch", adoptBranch,
				"--event", "push", "--limit", "20", "--json", "databaseId,headSha,status,conclusion")
			if err != nil {
				return err
			}
			var runs []ghRun
			if err := json.Unmarshal([]byte(lj), &runs); err != nil {
				return &exitError{2, fmt.Errorf("gh run list: %w", err)}
			}
			var found *ghRun
			for i := range runs {
				if runs[i].HeadSHA == sha { // the list is newest first
					found = &runs[i]
					break
				}
			}
			if found == nil {
				return &exitError{2, fmt.Errorf("no push run of fuzz.yml for %s (the run on this branch is for another commit, or has not started)", sha)}
			}
			if found.Status != "completed" {
				return &exitError{2, fmt.Errorf("run %d is %s, not completed", found.DatabaseID, found.Status)}
			}
			id := strconv.FormatInt(found.DatabaseID, 10)
			vj, err := run("gh", "run", "view", id, "--repo", slug, "--json", "jobs")
			if err != nil {
				return err
			}
			var jobs ghJobs
			if err := json.Unmarshal([]byte(vj), &jobs); err != nil {
				return &exitError{2, fmt.Errorf("gh run view: %w", err)}
			}
			if len(jobs.Jobs) == 0 {
				return &exitError{2, fmt.Errorf("run %d has no jobs: a run that never started is not a pass", found.DatabaseID)}
			}
			for _, j := range jobs.Jobs {
				if j.Conclusion != "success" {
					return &exitError{2, fmt.Errorf("job %q of run %d concluded %q", j.Name, found.DatabaseID, j.Conclusion)}
				}
			}
			log, err := run("gh", "run", "view", id, "--repo", slug, "--log")
			if err != nil {
				return err
			}
			ok := map[string]bool{}
			crashed := false
			for _, line := range strings.Split(log, "\n") {
				job, _, _ := strings.Cut(line, "\t")
				if m := crashRe.FindStringSubmatch(line); m != nil {
					crashed = true
					fmt.Fprintf(out, "CRASH job %q: %s %s corpus %s\n", job, m[1], m[2], m[3])
				}
				if m := summaryRe.FindStringSubmatch(line); m != nil {
					n, _ := strconv.Atoi(m[1])
					p, _ := strconv.Atoi(m[2])
					if m[4] != "0" {
						crashed = true
						fmt.Fprintf(out, "CRASH job %q: %s\n", job, strings.TrimSpace(m[0]))
					} else if m[3] == "0" && n == p && n > 0 {
						ok[job] = true
					}
				}
			}
			if crashed {
				return &exitError{code: 1}
			}
			for _, j := range jobs.Jobs {
				if !ok[j.Name] {
					return &exitError{2, fmt.Errorf("job %q of run %d has no \"N targets: N PASS, 0 FAIL, 0 CRASH\" line", j.Name, found.DatabaseID)}
				}
			}
			wfPath := filepath.Join(dir, ".github", "workflows", "fuzz.yml")
			b, err := os.ReadFile(wfPath)
			if err != nil {
				return &exitError{2, err}
			}
			t, err := removeTrigger(string(b))
			if err != nil {
				return &exitError{2, err}
			}
			if err := os.WriteFile(wfPath, []byte(t), 0o644); err != nil {
				return &exitError{2, err}
			}
			if _, err := run("git", "commit", "-a", "-m", msgRemove); err != nil {
				return err
			}
			if _, err := run("gitpush", "origin", adoptBranch); err != nil {
				return err
			}
			fmt.Fprintf(out, "verified run %d (%d jobs), trigger removed and pushed\n", found.DatabaseID, len(jobs.Jobs))
			return nil
		},
	}
	cmd.Flags().StringVar(&dir, "dir", ".", "clone of the repository")
	return cmd
}
